//全角 → 半角 (英数字)
function alphanumeric_ZENKAKU_to_HANKAKU (str) {

   str = str.replace(/[Ａ-Ｚａ-ｚ０-９]/g, function(s) {
      return String.fromCharCode(s.charCodeAt(0) - 0xFEE0);
   });

   return str;

}




//半角 → 全角 (英数字)
function alphanumeric_HANKAKU_to_ZENKAKU (str) {

   str = str.replace(/[A-Za-z0-9]/g, function(s) {
      return String.fromCharCode(s.charCodeAt(0) + 0xFEE0);
   });

   return str;

}




